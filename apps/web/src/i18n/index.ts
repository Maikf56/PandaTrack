/**
 * 翻译函数：模板与脚本通用。
 * - 词典缺失时回退显示 key（便于在页面上一眼发现漏词条）。
 * - 支持 {name} 占位符插值。
 * - 渲染期间读取 locale.value，语言切换自动触发重渲染。
 */
export function t(key: string, params?: Record<string, string | number>): string {
  const entry = dict[key]
  const text = entry ? entry[locale.value] : key
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (m, k: string) =>
    params[k] !== undefined ? String(params[k]) : m,
  )
}

/** 段头短日期：zh 为「6月18日 08:11」，en 为「06-18 08:11」。 */
export function fmtShortDate(d: Date): string {
  const hm = `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`
  const m = d.getMonth() + 1
  const day = d.getDate()
  return locale.value === 'zh'
    ? `${m}月${day}日 ${hm}`
    : `${String(m).padStart(2, '0')}-${String(day).padStart(2, '0')} ${hm}`
}
