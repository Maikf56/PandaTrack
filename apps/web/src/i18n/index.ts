/**
 * 整站 i18n（zh/en）：轻量词典方案，不引入 vue-i18n 依赖。
 * - UI 文案是固定字符串，走静态词典而非机翻（与「状态标签走静态字典」
 *   同一原则：质量、速度、零服务端依赖）。
 * - 动态内容（轨迹描述）的 en↔zh 机翻由后端 LibreTranslate provider 负责，
 *   与本模块解耦（见 apps/api/src/api/translate.py）。
 * - locale 持久化到 localStorage('pt_locale')；首次访问按浏览器语言选择。
 * - 轨迹翻译语言复用 composables/session.ts 的 lang/setLang('pt_lang')。
 */
import { ref } from 'vue'

export type Locale = 'zh' | 'en'

const LOCALE_KEY = 'pt_locale'

function loadLocale(): Locale {
  try {
    const saved = localStorage.getItem(LOCALE_KEY)
    if (saved === 'zh' || saved === 'en') return saved
    return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
  } catch {
    return 'zh'
  }
}

export const locale = ref<Locale>(loadLocale())

export function setLocale(l: Locale): void {
  locale.value = l
  try {
    localStorage.setItem(LOCALE_KEY, l)
    document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'
  } catch {
    /* 存储不可用时仅本会话生效 */
  }
}

export function toggleLocale(): void {
  setLocale(locale.value === 'zh' ? 'en' : 'zh')
}

